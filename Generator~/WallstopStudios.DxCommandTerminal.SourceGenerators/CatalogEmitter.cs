            + BindingFlagsType
            + ".Public | "
            + BindingFlagsType
            + ".NonPublic";

        private const string BinderFieldNameFormat = "_boundHandler{0}";
        private const string BinderMethodNameFormat = "BindHandler{0}";

        internal static string Emit(List<CommandModel> commands)
        {
