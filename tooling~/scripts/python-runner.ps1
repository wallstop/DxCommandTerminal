function Invoke-ToolingPython {
    param(
        [Parameter(Mandatory)][string]$ToolingRoot,
        [Parameter(Mandatory)][string[]]$PythonArguments,
        [Parameter(Mandatory)][string]$ErrorPrefix,
        [switch]$RawOutput
    )

    $runnerCommand = $null
    $runnerPrefix = @()
    foreach ($candidate in @(@('uv', 'run', '--project', $ToolingRoot, 'python'), @('python'), @('python3'))) {
        if (-not (Get-Command $candidate[0] -ErrorAction SilentlyContinue)) { continue }
        if ($candidate[0] -ne 'uv') {
            # WindowsApps aliases can resolve without an installed interpreter.
            try {
                $global:LASTEXITCODE = 1
                & $candidate[0] -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' *> $null
                if ($global:LASTEXITCODE -ne 0) { continue }
            }
            catch { continue }
        }
        $runnerCommand = $candidate[0]
        if ($candidate.Count -gt 1) { $runnerPrefix = $candidate[1..($candidate.Count - 1)] }
        break
    }
    if ($null -eq $runnerCommand) {
        $message = "[$ErrorPrefix] ERROR: no working runner found (need uv or Python 3.11+ on PATH)"
        if ($RawOutput) { [Console]::Error.WriteLine($message) }
        else { Write-Host $message -ForegroundColor Red }
        return 1
    }

    $previousEnvironment = $env:UV_PROJECT_ENVIRONMENT
    $previousVirtualEnvironment = $env:VIRTUAL_ENV
    $previousEncoding = [Console]::OutputEncoding
    try {
        if ($runnerCommand -eq 'uv' -and [string]::IsNullOrEmpty($previousEnvironment)) {
            $platform = if ($IsWindows) { 'windows' } elseif ($IsMacOS) { 'macos' } else { 'linux' }
            $scope = if ((Test-Path -LiteralPath '/.dockerenv') -or (Test-Path -LiteralPath '/run/.containerenv')) { 'container' } else { 'host' }
            $architecture = [System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString().ToLowerInvariant()
            $env:UV_PROJECT_ENVIRONMENT = Join-Path $ToolingRoot ".venv-$scope-$platform-$architecture"
        }
        if ($runnerCommand -eq 'uv') { $env:VIRTUAL_ENV = $null }
        if ($RawOutput) {
            $startInfo = [System.Diagnostics.ProcessStartInfo]::new()
            $startInfo.FileName = (Get-Command $runnerCommand -CommandType Application -ErrorAction Stop).Source
            $startInfo.UseShellExecute = $false
            $startInfo.RedirectStandardOutput = $true
            foreach ($argument in (@($runnerPrefix) + @($PythonArguments))) {
                $startInfo.ArgumentList.Add($argument)
            }
            $process = [System.Diagnostics.Process]::new()
            $process.StartInfo = $startInfo
            try {
                [void]$process.Start()
                # The generated bytes must bypass host decoding and newline conversion.
                $process.StandardOutput.BaseStream.CopyTo([Console]::OpenStandardOutput())
                $process.WaitForExit()
                return $process.ExitCode
            }
            finally { $process.Dispose() }
        }
        [Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false)
        & $runnerCommand @runnerPrefix @PythonArguments | ForEach-Object { Write-Host $_ }
        return $global:LASTEXITCODE
    }
    finally {
        $env:UV_PROJECT_ENVIRONMENT = $previousEnvironment
        $env:VIRTUAL_ENV = $previousVirtualEnvironment
        [Console]::OutputEncoding = $previousEncoding
    }
}
